using System.Globalization;

namespace PixelFlux.Core.Localisation;

/// <summary>
/// Every piece of user-visible text in PixelFlux, and the machinery to say it in another
/// language.
/// </summary>
/// <remarks>
/// <para>
/// A plain dictionary per language rather than .resx satellite assemblies. The reasons are
/// specific rather than contrarian: PixelFlux ships as a single unpackaged executable, and
/// satellite assemblies mean a folder of per-culture DLLs that has to survive copying,
/// zipping, and being moved between machines; a translator working on .resx needs Visual
/// Studio; and the catalogue below is directly greppable, which is what makes it possible to
/// prove no English is left hardcoded in the components.
/// </para>
/// <para>
/// <b>Keys are dotted and semantic</b> — <c>gallery.empty.title</c>, not <c>Msg17</c> and not
/// the English text itself. Using the English as the key looks convenient and then locks every
/// language to English's grammar the moment a string needs to change.
/// </para>
/// <para>
/// <b>Missing translations fall back to English and are never blank.</b> A partially translated
/// build is the normal state of any real localisation effort, and a UI that shows empty buttons
/// for the untranslated half is worse than one that shows English.
/// </para>
/// </remarks>
public sealed class Strings
