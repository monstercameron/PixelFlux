    private Dictionary<string, string> _active = Catalogue["en"];

    /// <summary>The language currently in use.</summary>
    public Language Current { get; private set; } = Available[0];

    /// <summary>Whether the current language is written right to left.</summary>
    public bool IsRightToLeft => Current.RightToLeft;

    /// <summary>Raised after the language changes, so open views can re-render.</summary>
    public event Action? LanguageChanged;

    /// <summary>
    /// Selects a language, falling back to the closest available one.
    /// </summary>
    /// <param name="code">A BCP-47 code such as <c>es</c>, <c>es-MX</c>, or <c>ja-JP</c>.</param>
    /// <remarks>
    /// Region is stripped before matching, so <c>es-MX</c> and <c>es-ES</c> both land on Spanish
    /// rather than falling all the way back to English. Shipping every regional variant is how a
    /// localisation effort becomes unmaintainable; matching the language and ignoring the region
    /// covers almost every real user.
    /// </remarks>
    public void Use(string code)
    {
        string language = (code ?? "en").Split('-')[0];

        Language match = Available.FirstOrDefault(
            l => l.Code.Equals(language, StringComparison.OrdinalIgnoreCase),
            Available[0]);

        Current = match;
        _active = Catalogue[match.Code];

        // Dates, numbers, and the sort order of any list the UI builds must follow the chosen
        // language too. Setting only the strings produces the uncanny result of Japanese labels
        // above American-formatted dates.
        var culture = CultureInfo.GetCultureInfo(match.Code);
        CultureInfo.DefaultThreadCurrentCulture = culture;
        CultureInfo.DefaultThreadCurrentUICulture = culture;
        CultureInfo.CurrentCulture = culture;
        CultureInfo.CurrentUICulture = culture;

        LanguageChanged?.Invoke();
    }

    /// <summary>
    /// Adopts the operating system's language, if PixelFlux speaks it.
    /// </summary>
    /// <remarks>
    /// The <c>PIXELFLUX_LANG</c> environment variable overrides it. That exists so the app can
    /// be launched straight into Arabic or Japanese to check the layout, without clicking
    /// through the UI or changing the machine's own locale — which is the only practical way to
    /// catch a right-to-left regression before a speaker of the language does.
    /// </remarks>
    public void UseSystemLanguage()
        => Use(Environment.GetEnvironmentVariable("PIXELFLUX_LANG") ?? CultureInfo.CurrentUICulture.Name);

    /// <summary>Looks up a string by key.</summary>
    /// <param name="key">A dotted key, for example <c>gallery.empty.title</c>.</param>
    /// <returns>
    /// The translation, the English text if this language has not translated it, or the key
    /// itself if no language defines it.
    /// </returns>
    /// <remarks>
    /// Returning the key for a genuinely missing entry is deliberate. A blank label is invisible
    /// in testing and ships; a label reading <c>filter.camera</c> is impossible to miss and says
    /// exactly which entry to add.
    /// </remarks>
    public string this[string key]
    {
        get
        {
            if (_active.TryGetValue(key, out string? value))
            {
                return value;
            }

            return Catalogue["en"].TryGetValue(key, out string? english) ? english : key;
        }
    }

    /// <summary>Looks up a string and substitutes positional arguments into it.</summary>
    /// <param name="key">A dotted key whose text contains <c>{0}</c>-style placeholders.</param>
    /// <param name="args">Values to substitute.</param>
    /// <returns>The formatted string.</returns>
    /// <remarks>
    /// Placeholders rather than concatenation, always. Word order differs between languages —
    /// Arabic and Japanese both place the count differently from English — and a UI assembled by
    /// gluing fragments together can only ever be right in the language it was written in.
    /// </remarks>
    public string Format(string key, params object[] args)
        => string.Format(CultureInfo.CurrentCulture, this[key], args);

    /// <summary>Every key defined in English. Used by the test that proves no language has drifted.</summary>
    public static IReadOnlyCollection<string> AllKeys => Catalogue["en"].Keys;

    /// <summary>Keys defined for a language. Used by the coverage test.</summary>
    /// <param name="code">Language code.</param>
    /// <returns>The keys that language defines.</returns>
    public static IReadOnlyCollection<string> KeysFor(string code)
        => Catalogue.TryGetValue(code, out Dictionary<string, string>? map) ? map.Keys : [];
