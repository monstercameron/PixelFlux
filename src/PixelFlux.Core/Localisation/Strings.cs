    /// <param name="Code">BCP-47 culture code, for example <c>pt-BR</c>.</param>
    /// <param name="EnglishName">Name in English, for logs and settings search.</param>
    /// <param name="NativeName">Name as speakers of it write it — what the picker shows.</param>
    /// <param name="RightToLeft">Whether the script runs right to left.</param>
    public readonly record struct Language(string Code, string EnglishName, string NativeName, bool RightToLeft);

